'use strict';
const assert = require('assert');
const {CursorIdle} = require('../standalone/cursor_idle');
let time = 0, pulses = 0;
const icons = [];
const cursor = new CursorIdle(30, state => icons.push(state), () => pulses++, () => time);
cursor.scope(true);
cursor.tick();
assert.deepEqual(icons, [], 'entering HDMI without activity should not show the cursor');
cursor.activity();
assert.deepEqual(icons, [true], 'real motion must immediately show the cursor');
for (time = 100; time < 30000; time += 100) cursor.tick();
assert.equal(cursor.visible, true, 'native fade must not shorten the requested timeout');
assert(pulses > 5);
cursor.tick();
assert.deepEqual(icons, [true, false], 'hide at 30 seconds, regardless of keepalives');
time++;
cursor.activity();
assert.equal(cursor.visible, true, 'wake immediately after idle');
cursor.scope(false);
const before = pulses;
time += 1000;
cursor.activity();
cursor.tick();
assert.equal(cursor.visible, false);
assert.equal(pulses, before, 'no keepalive outside the configured HDMI');
{
  let clock = 0;
  const quick = new CursorIdle(5, () => {}, () => {}, () => clock);
  quick.scope(true);
  quick.activity();
  clock = 4999;
  quick.tick();
  assert.equal(quick.visible, true);
  clock = 5000;
  quick.tick();
  assert.equal(quick.visible, false, 'five-second configuration must hide at five seconds');
  quick.activity();
  assert.equal(quick.visible, true, 'five-second configuration must wake on activity');
}
console.log('Cursor visibility and configurable idle checks passed');
